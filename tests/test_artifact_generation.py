def _setup(tmp_path):
    ledger = SQLiteRequirementLedger(tmp_path / "ledger.sqlite3")
    requirements = RequirementService(ledger)
    requirements.create_project("alpha", "Alpha", actor="orchestrator")
    requirement = requirements.register(
        "alpha",
        RequirementDraft(
            title="Generate immutable artifacts",
            statement="The server shall generate read-only views from the canonical ledger.",
            category="functional",
            rationale="Artifact generation baseline.",
            source_anchor="baseline/requirements.md:10",
        ),
        actor="orchestrator",
    )
    requirements.set_lifecycle(
        "alpha",
        requirement["requirement_id"],
        LifecycleStatus.IMPLEMENTED,
        actor="orchestrator",
        reason="fixture implementation",
    )
    requirements.record_verification(
        "alpha",
        requirement["requirement_id"],
        VerificationDraft(
            kind=VerificationKind.DETERMINISTIC,
            outcome=VerificationOutcome.PASSED,
            reference="pytest tests/test_artifact_generation.py",
        ),
        actor="orchestrator",
    )
    goals = GoalGraphService(ledger)
    goals.add_use_case(
        "alpha",
        UseCaseDraft(
            title="Generate a catalogue",
            actor="orchestrator",
            objective="obtain a source-of-truth lifecycle view",
            observable_outcome="the generated view identifies its canonical provenance",
            source_anchor=SourceAnchor("baseline/SRS.md", 20, 32, "UC-ALPHA-001"),
        ),
        actor="orchestrator",
    )
    lifecycle = LifecycleControlService(
        requirements=ledger,
        goals=ledger,
        grounding_audits=ledger,
        control=ledger,
    )
    lifecycle.promote_milestone(
        "alpha",
        MilestoneDraft(
            name="alpha-1",
            requirement_ids=(requirement["requirement_id"],),
            prerequisite_requirement_ids=(),
            entry_policy={"requires": ["accepted baseline"]},
            exit_policy={"requires": ["deterministic verification"]},
            risk_disposition="none",
            acceptance_evidence=("campaign:alpha-1",),
        ),
        actor="orchestrator",
    )
    lifecycle.audit_phase(
        "alpha",
        PhaseAuditScope("project-default"),
        actor="orchestrator",
    )
    return ledger, requirement


def test_generation_is_profile_defined_versioned_mapped_and_idempotent(tmp_path):
    ledger, requirement = _setup(tmp_path)
    service = ArtifactGenerationService(
        profiles=StandardProfileRegistry(),
        requirements=ledger,
        goals=ledger,
        control=ledger,
        ledger_versions=ledger,
        artifacts=ledger,
    )
    ledger_version = ledger.ledger_version("alpha")

    generation = service.generate(
        "alpha",
        profile_id="fow-srs-markdown-v1",
        actor="orchestrator",
        request_id="artifact-batch-1",
    )

    assert generation.generation_id == 1
    assert generation.source_ledger_version == ledger_version
    assert {artifact.kind for artifact in generation.artifacts} == set(ArtifactKind) - {ArtifactKind.IMPLEMENTATION_PLAN}
    requirements_catalogue = next(
        artifact
        for artifact in generation.artifacts
        if artifact.kind == ArtifactKind.REQUIREMENTS_CATALOGUE
    )
    assert "Generated by Flower MCP" in requirements_catalogue.content
    assert requirement["requirement_id"] in requirements_catalogue.content
    assert "canonical SQLite lifecycle ledger" in requirements_catalogue.content
    assert requirements_catalogue.mappings[0].source_anchor == "baseline/requirements.md:10"
    phase_audit = next(
        artifact for artifact in generation.artifacts if artifact.kind == ArtifactKind.PHASE_AUDIT
    )
    assert "| 1 | project-default |" in phase_audit.content

    stored = ledger.artifact_generations("alpha")
    assert stored[0]["generation_id"] == generation.generation_id
    stored_catalogue = next(
        artifact
        for artifact in stored[0]["artifacts"]
        if artifact["artifact_kind"] == ArtifactKind.REQUIREMENTS_CATALOGUE.value
    )
    assert stored_catalogue["content_sha256"] == requirements_catalogue.content_sha256
    assert stored_catalogue["mappings"] == [
        {
            "canonical_kind": "requirement",
            "canonical_id": requirement["requirement_id"],
            "source_anchor": "baseline/requirements.md:10",
        }
    ]

    repeated = service.generate(
        "alpha",
        profile_id="fow-srs-markdown-v1",
        actor="orchestrator",
        request_id="artifact-batch-1",
    )
    assert repeated.generation_id == generation.generation_id
    assert len(ledger.artifact_generations("alpha")) == 1


def test_generated_goal_and_multiline_requirement_references_keep_semantic_blocks(tmp_path):
    from flow_of_work_mcp import SequenceDraft

    ledger, requirement = _setup(tmp_path)
    RequirementService(ledger).revise("alpha", requirement["requirement_id"], RequirementDraft(
        title="Complete multiline requirement", statement="FIRST_REQUIREMENT_LINE\nSECOND_REQUIREMENT_LINE with `code` | pipe.",
        category="functional", rationale="Keep physical lines.", source_anchor="baseline/requirements.md:10"),
        actor="engineer", rationale="Synthetic multiline presentation fixture.")
    sequence = GoalGraphService(ledger).add_sequence("alpha", SequenceDraft(
        title="Ordered generation sequence", participants=("SYNTHETIC_USER", "SYNTHETIC_SERVER"),
        normal_steps=("FIRST_NORMAL_STEP\nSTEP_CONTINUATION", "SECOND_NORMAL_STEP"),
        alternate_steps=("ALTERNATE_PATH",), failure_steps=("FAILURE_PATH",), expected_effects=("OBSERVED_EFFECT",),
        source_anchor=SourceAnchor("baseline/sequences.md", 15, 25, "SEQ-ALPHA-001")), actor="engineer")
    service = ArtifactGenerationService(profiles=StandardProfileRegistry(), requirements=ledger,
        goals=ledger, control=ledger, ledger_versions=ledger, artifacts=ledger)
    graph_before = deepcopy(ledger.goal_graph("alpha"))
    requirements_before = deepcopy(ledger.traceability_matrix("alpha"))
    generation = service.generate("alpha", profile_id="fow-srs-markdown-v1", actor="engineer", request_id="readable-artifacts")
    by_kind = {artifact.kind:artifact for artifact in generation.artifacts}
    for kind in (ArtifactKind.SRS, ArtifactKind.REQUIREMENTS_CATALOGUE):
        text = by_kind[kind].content
        assert "FIRST_REQUIREMENT_LINE" in text and "SECOND_REQUIREMENT_LINE" in text
        statement_lines = text.splitlines()
        first_line = next(index for index, line in enumerate(statement_lines) if "FIRST_REQUIREMENT_LINE" in line)
        assert "SECOND_REQUIREMENT_LINE" in statement_lines[first_line + 1]
        assert "| Statement |" not in text
        html = MarkdownIt("commonmark", {"html":False}).render(text)
        assert "FIRST_REQUIREMENT_LINE\nSECOND_REQUIREMENT_LINE" in html
        assert "<pre><code" not in html
        assert "baseline/requirements.md:10" in text
        assert "Verification" in text and "Evidence" in text
    for kind in (ArtifactKind.SRS, ArtifactKind.SEQUENCE_SPECIFICATION):
        text = by_kind[kind].content
        for value in ("FIRST_NORMAL_STEP", "STEP_CONTINUATION", "SECOND_NORMAL_STEP", "ALTERNATE_PATH",
                      "FAILURE_PATH", "OBSERVED_EFFECT", "SYNTHETIC_USER", "SYNTHETIC_SERVER"):
            assert value in text
        assert text.index("FIRST_NORMAL_STEP") < text.index("SECOND_NORMAL_STEP")
        assert '"normal_steps"' not in text and "| Payload |" not in text
        assert "<ol>" in MarkdownIt("commonmark").render(text)
    assert "obtain a source-of-truth lifecycle view" in by_kind[ArtifactKind.USE_CASE_SPECIFICATION].content
    sequence_node = next(node for node in graph_before["nodes"] if node["goal_node_id"] == sequence["goal_node_id"])
    mappings = by_kind[ArtifactKind.SEQUENCE_SPECIFICATION].mappings
    assert len(mappings) == 1
    assert mappings[0].source_anchor == json.dumps(sequence_node["source_anchor"], sort_keys=True)
    for artifact in generation.artifacts:
        assert artifact.content_sha256 == sha256(artifact.content.encode()).hexdigest()
    assert ledger.goal_graph("alpha") == graph_before
    assert ledger.traceability_matrix("alpha") == requirements_before


def test_historical_artifact_content_and_replay_are_never_rewritten_by_new_renderer(tmp_path):
    from flow_of_work_mcp.core.domain.artifacts import ArtifactDraft, ArtifactGeneration, ArtifactMapping

    ledger, requirement = _setup(tmp_path)
    historical = ArtifactDraft(ArtifactKind.REQUIREMENTS_CATALOGUE,
        '# Historical reference\n\n| Payload |\n| --- |\n| {"preserved": "original bytes"} |',
        (ArtifactMapping("requirement", requirement["requirement_id"], "baseline/requirements.md:10"),))
    stored = ledger.record_artifact_generation(ArtifactGeneration(
        "alpha", "fow-srs-markdown-v1", "1.0", ledger.ledger_version("alpha"),
        "2026-01-01T00:00:00+00:00", (historical,)), actor="fixture", request_id="historical-render")
    before = deepcopy(ledger.artifact_generations("alpha"))
    service = ArtifactGenerationService(profiles=StandardProfileRegistry(), requirements=ledger,
        goals=ledger, control=ledger, ledger_versions=ledger, artifacts=ledger)
    replayed = service.generate("alpha", profile_id="fow-srs-markdown-v1", actor="engineer", request_id="historical-render")
    assert replayed == stored
    assert ledger.artifact_generations("alpha") == before
    fresh = service.generate("alpha", profile_id="fow-srs-markdown-v1", actor="engineer", request_id="new-readability-generation")
    assert fresh.generation_id != stored.generation_id
    assert ledger.artifact_generations("alpha")[0] == before[0]
    current_catalogue = next(artifact for artifact in fresh.artifacts
                             if artifact.kind == ArtifactKind.REQUIREMENTS_CATALOGUE)
    assert current_catalogue.content != historical.content and "| Payload |" not in current_catalogue.content
    assert stored.artifacts[0].content_sha256 == historical.content_sha256
